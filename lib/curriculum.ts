// Static curriculum lives in Git. Only task IDs and personal notes are persisted.
export type CurriculumWeek = {
  number: number;
  milestone: number;
  title: string;
  objectives: string[];
  newProblems: number;
  days: { id: string; day: number; task: string }[];
};
function week(
  number: number,
  milestone: number,
  title: string,
  newProblems: number,
  objectives: string[],
  tasks: string[],
): CurriculumWeek {
  return {
    number,
    milestone,
    title,
    newProblems,
    objectives,
    days: tasks.map((task, i) => ({
      id: `w${String(number).padStart(2, "0")}-d${i + 1}`,
      day: (number - 1) * 7 + i + 1,
      task,
    })),
  };
}
